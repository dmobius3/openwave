"""Shared library for the stage-1 audit. Own implementations only.

Exact quaternion arithmetic over Q(sqrt5), the group generated by q1, q2,
SU(2) identifications, D^j (exact sympy and numeric numpy), CG coefficients
(Racah formula, exact) plus an independent highest-weight/lowering construction,
and a check harness in which every PASS has a mutation that must FAIL.
"""
