"""Writes RESULTS.md: the one-command freeze surface.

Runs every check script and both precisions of m810_exact.py itself, so nothing is read from an earlier
shell action. Refuses to write unless every script ends on its pass line, the 60- and 100-digit runs give
identical fractions, and the 100-digit residual clears its threshold; then recomputes every value
in-process and checks it against the 100-digit identification. The fractions are candidate exact values
(rational identification, not a symbolic derivation), to be reproduced exactly by the blind run.
"""
import json
import os
import re
import subprocess
from fractions import Fraction

SCRIPTS = {'m810_selftest.py': 'ALL PASS', 'm810_parent.py': 'ALL PASS', 'm810_levels.py': 'ALL CHECKS PASS',
           'm810_gates.py': 'ALL GATES PASS, ALL ARMS FAIL AS REQUIRED', 'm810_zeros.py': 'ALL ZEROS EXPLAINED'}
os.makedirs('out', exist_ok=True)
for stale in ('out/zeros.json', 'out/exact_dps60.txt', 'out/exact_dps100.txt'):
    if os.path.exists(stale):
        os.remove(stale)


def run(script, dps=None):
    env = dict(os.environ)
    if dps:
        env['M810_DPS'] = str(dps)
    return subprocess.run(['python3', script], capture_output=True, text=True, check=True, env=env).stdout


def parse(out):
    table, sector, ray = {}, None, None
    for line in out.splitlines():
        m = re.match(r'\s*=== sector (\S+) ===', line)
        if m:
            sector = m.group(1)
            continue
        m = re.match(r'\s+(.+?): \|P6 N\|\^2 = Q_d\^2 exactly: (\w+)', line)
        if m:
            ray = m.group(1)
            assert m.group(2) == 'True', (sector, ray)
            continue
        if '||P_n N||^2:' in line:
            table[(sector, ray)] = {int(n): Fraction(f) for n, f in re.findall(r'n=(\d+): (\d+/\d+|\d+)', line)}
    return table


status = {}
for script, want in SCRIPTS.items():
    out = run(script)
    open(f'out/{script[:-3]}.txt', 'w').write(out)
    last = [l for l in out.splitlines() if l.strip()][-1].strip()
    assert last == want, (script, last)
    status[script] = (out.count('[PASS]') + out.count('[ok]') + out.count('[explained]'), last)
ident = {}
for dps in (60, 100):
    out = run('m810_exact.py', dps)
    open(f'out/exact_dps{dps}.txt', 'w').write(out)
    res = float(re.search(r'worst rational-identification residual: (\S+)', out).group(1))
    assert res < 10.0 ** -(dps - 15), (dps, res)
    ident[dps] = (parse(out), res)
assert len(ident[60][0]) == 8 and ident[60][0] == ident[100][0]
zeros = json.load(open('out/zeros.json'))

os.environ['M810_DPS'] = '60'
import mpmath as mp
import m810_exact as E

LABEL = {'3p': "3′", '4': '4'}
LEVELS = {'3p': [10, 14, 16, 18], '4': [8, 12, 14, 16, 18]}
R, maxden = {}, 0
for sector, d in (('3p', 3), ('4', 4)):
    for name, spec in E.RAYS.items():
        u = [mp.mpc(0)] * 7
        for m, c in spec.items():
            u[E.IX[m]] = mp.mpc(c)
        scale = mp.sqrt(mp.mpf(7) / d / sum(abs(x) ** 2 for x in u))
        lv, _ = E.level_norms([x * scale for x in u], E.PROJ[sector])
        ex = {}
        for n, x in lv.items():
            f, err = E.as_fraction(x)
            assert err < mp.mpf(10) ** -45
            ex[n] = f
        assert {n: f for n, f in ex.items() if n != 6 and f != 0} == ident[100][0][(sector, name)]
        maxden = max([maxden] + [f.denominator for f in ex.values()])
        Q = 1 + Fraction(E.TABLE[name], E.DEN[sector])
        assert ex[6] == Q * Q and all(ex[n] == 0 for n in ex if n not in LEVELS[sector] + [6])
        xi = {n: ex[n] / E.den(n) ** 2 for n in LEVELS[sector]}
        lam4 = -3 * sum(ex[n] / E.den(n) for n in LEVELS[sector])
        assert lam4 < 0 and set(zeros[f'{sector}|{name}']['zero']) == {n for n in LEVELS[sector] if ex[n] == 0}
        R[(sector, name)] = dict(Q=Q, lam4=lam4, xi=xi, xi2=sum(xi.values()))

L = ['# M8.10 fresh derivation: values to freeze (local)', '',
     'Generated by `m810_results.py`, which runs every check script and both precisions itself; every value below is '
     'recomputed from the algebra, none transcribed. Conventions: g = 1, R = 1, normalized Haar measure, section normalized '
     'so that ∫|Φ|² = 1. λ₂ = g·Q_d; ξ = −g A⁻¹ Π_⊥ N(Φ); λ₄ = −3g² Σₙ ‖Πₙ N(Φ)‖² / (n(n+2) − 48). The values scale as g, g and g².', '',
     f'**Status of the fractions: candidate exact values.** Each level norm ‖Πₙ N(Φ)‖² is computed by finite algebra '
     f'(Clebsch–Gordan coefficients and 2I group averages) in 60- and 100-digit arithmetic and identified as a rational with '
     f'denominator at most 10¹⁶. The two precisions give identical fractions; the worst residual at 100 digits is {ident[100][1]:.2e} '
     f'against a threshold of 10⁻⁸⁵, and the largest identified denominator is {maxden}. Conditional on those identified level-norm fractions, the λ₄ and ‖ξ‖² '
     f'fractions follow by exact rational arithmetic. The level norms need not be rational a priori, since the sector '
     f'projectors involve the golden ratio, so that they come out rational is itself a finding. This is rational identification, not a symbolic derivation: the blind run is asked to reproduce the '
     f'fractions exactly, and a symbolic derivation would promote them to exact results.', '',
     'Independence: this folder imports numpy, scipy, mpmath and its own modules only; nothing from M8_DYNAMICS/build, '
     'the openwave repository, or any C/C2 room.', '']
for sector in ('3p', '4'):
    L += [f'## Sector {LABEL[sector]}', '', '| ray | λ₂ = Q_d | λ₄/g² | λ₄/g² (decimal) | ‖ξ‖²/g² |', '|---|---|---|---|---|']
    for name in E.RAYS:
        r = R[(sector, name)]
        L.append(f"| {name} | {r['Q']} | {r['lam4']} | {float(r['lam4']):.12e} | {r['xi2']} |")
    L += ['', '| ray | ' + ' | '.join(f'‖Π_{n} ξ‖²/g²' for n in LEVELS[sector]) + ' |', '|---' * (len(LEVELS[sector]) + 1) + '|']
    for name in E.RAYS:
        L.append(f'| {name} | ' + ' | '.join(str(R[(sector, name)]['xi'][n]) for n in LEVELS[sector]) + ' |')
    L.append('')
L += ['## Sector comparison', '', '| ray | λ₄(3′)/λ₄(4) | decimal |', '|---|---|---|']
for name in E.RAYS:
    q = R[('3p', name)]['lam4'] / R[('4', name)]['lam4']
    L.append(f'| {name} | {q} | {float(q):.6f} |')
L += ['', '## Zeros', '',
      'A level vanishes identically when the character by which the ray\'s stabilizer H acts on u has no isotypic part in V_J '
      '(n = 2J). Time reversal is antiunitary and not in H; the level-16 zeros that H does not force are the paper\'s '
      'Proposition 3.3 (M8.1.2\'s A5).', '',
      '| sector | ray | zero levels | forced by H | time reversal only |', '|---|---|---|---|---|']
fmt = lambda v: ', '.join(map(str, v)) if v else 'none'
for sector in ('3p', '4'):
    for name in E.RAYS:
        z = zeros[f'{sector}|{name}']
        L.append(f"| {LABEL[sector]} | {name} | {fmt(z['zero'])} | {fmt([n for n in z['forced_by_H'] if n in z['zero']])} | {fmt(z['time_reversal_only'])} |")
L += ['', '## Gates', '']
for script, (n, last) in status.items():
    L.append(f'- `{script}`: {n} checks, final line "{last}" (output in `out/{script[:-3]}.txt`)')
L.append(f'- `m810_exact.py`, run here at 60 and 100 digits: identical fractions; worst residuals {ident[60][1]:.2e} and '
         f'{ident[100][1]:.2e} (outputs in `out/exact_dps60.txt`, `out/exact_dps100.txt`)')
text = '\n'.join(L) + '\n'
assert '—' not in text
open('RESULTS.md', 'w', encoding='utf-8').write(text)
print('RESULTS.md written:', len(L), 'lines')
