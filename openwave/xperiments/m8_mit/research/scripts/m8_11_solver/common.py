def fibre_vectors():
    """mp versions of U1..U6 (unnormalized)."""
    s5 = mp.sqrt(mpf(12) / 25)
    c5 = mp.sqrt(mpf(13) / 25)
    z0 = mp.sqrt(mpf(23) / 10)
    U = {}
    U['U1'] = basis_vec(3, 3)
    U['U2'] = basis_vec(3, 0)
    U['U3'] = vadd(basis_vec(3, 2), basis_vec(3, -2))
    U['U4'] = vadd(basis_vec(3, 3), basis_vec(3, -3))
    U['U5'] = vadd(vscale(basis_vec(3, 2), c5), vscale(basis_vec(3, -3), s5))
    U['U6'] = vadd(vadd(basis_vec(3, 3), basis_vec(3, -3)), vscale(basis_vec(3, 0), z0))
    return U


def tangent_vectors(U):
    """Fibre directions of e_t (at U5) and tau_x (at U6), unnormalized, cf. section 1.6."""
    s5 = mp.sqrt(mpf(12) / 25)
    c5 = mp.sqrt(mpf(13) / 25)
    et = vadd(vscale(basis_vec(3, 2), -s5), vscale(basis_vec(3, -3), c5))
    u6 = U['U6']
    v0 = basis_vec(3, 0)
    tx = vadd(v0, u6, -vdot(u6, v0) / vnorm2(u6))
    return et, tx


# ----------------------------------------------------------------------------------
# identification of exact values from high-precision numerics
# ----------------------------------------------------------------------------------
MAXCOEFF_Q = 10 ** 30      # rational p/q: denominator bound (a spurious convergent would need
                           # |x - p/q| ~ 1/q^2 >= 1e-60, far above the 1e-68 tolerance at 80 digits)
MAXCOEFF_Q5 = 10 ** 10     # relations c0 x + c1 + c2 sqrt5 = 0
PRECISIONS = (80, 120)     # identification precisions (digits)


def _fmt_q5(c0, c1, c2):
    # value = -(c1 + c2 sqrt5)/c0
    a = Fraction(-c1, c0)
    b = Fraction(-c2, c0)
    if b == 0:
        return str(a)
    if a == 0:
        return '%s*sqrt(5)' % b
    return '%s%s%s*sqrt(5)' % (a, '+' if b > 0 else '-', abs(b))


def identify(x, field='Q5'):
    """Find an exact form for real x at the current precision (tolerance 10^-(dps-12)).
    Tries in order: 0; rational (|coefficients| <= 1e20); +-sqrt(rational); Q(sqrt5)
    (|coefficients| <= 1e10); +-sqrt(Q(sqrt5)).  Returns (string, residual) or (None, None)."""
    x = mp.re(x) if isinstance(x, mpc) else x
    tol = mpf(10) ** (-(mp.dps - 12))
    if abs(x) < tol:
        return '0', abs(x)

    def rat(y):
        # continued fraction convergents p/q with q <= MAXCOEFF_Q; accept the first with |y - p/q| < tol
        z = y
        p0, q0, p1, q1 = 0, 1, 1, 0
        for _ in range(200):
            a_ = int(mp.floor(z))
            p0, q0, p1, q1 = p1, q1, a_ * p1 + p0, a_ * q1 + q0
            if q1 > MAXCOEFF_Q:
                return None, None
            if abs(mpf(p1) / q1 - y) < tol * max(1, abs(y)):
                return (q1, -p1, 0), abs(mpf(p1) / q1 - y)
            frac = z - a_
            if frac == 0:
                return None, None
            z = 1 / frac
        return None, None

    def q5(y):
        rel = mp.pslq([y, 1, mp.sqrt(5)], maxcoeff=MAXCOEFF_Q5, maxsteps=200000, tol=tol)
        if rel and rel[0] != 0:
            val = -(rel[1] + rel[2] * mp.sqrt(5)) / rel[0]
            if abs(val - y) < tol * max(1, abs(y)):
                return tuple(rel), abs(val - y)
        return None, None

    sgn = '' if x > 0 else '-'
    rel, res = rat(x)
    if rel:
        return _fmt_q5(*rel), res
    rel, res = rat(x * x)
    if rel:
        return '%ssqrt(%s)' % (sgn, _fmt_q5(*rel)), res
    if field == 'Q5':
        rel, res = q5(x)
        if rel:
            return _fmt_q5(*rel), res
        rel, res = q5(x * x)
        if rel:
            return '%ssqrt(%s)' % (sgn, _fmt_q5(*rel)), res
    return None, None


