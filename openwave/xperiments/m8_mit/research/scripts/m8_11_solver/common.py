# Clebsch-Gordan coefficients, exact (Racah formula), integer spins
# ----------------------------------------------------------------------------------
_CG_EXACT = {}


def cg_exact(j1, m1, j2, m2, J, M):
    """Return (sign, value^2) with value = sign*sqrt(value^2), Condon-Shortley convention."""
    key = (j1, m1, j2, m2, J, M)
    if key in _CG_EXACT:
        return _CG_EXACT[key]
    if (m1 + m2 != M or not (abs(j1 - j2) <= J <= j1 + j2) or abs(m1) > j1 or abs(m2) > j2
            or abs(M) > J):
        res = (0, Fraction(0))
    else:
        pref = Fraction((2 * J + 1) * fac(J + j1 - j2) * fac(J - j1 + j2) * fac(j1 + j2 - J),
                        fac(j1 + j2 + J + 1))
        pref *= fac(J + M) * fac(J - M) * fac(j1 - m1) * fac(j1 + m1) * fac(j2 - m2) * fac(j2 + m2)
        S = Fraction(0)
        for k in range(0, j1 + j2 - J + 1):
            den = [k, j1 + j2 - J - k, j1 - m1 - k, j2 + m2 - k, J - j2 + m1 + k, J - j1 - m2 + k]
            if min(den) < 0:
                continue
            p = 1
            for x in den:
                p *= fac(x)
            S += Fraction((-1) ** k, p)
        res = ((S > 0) - (S < 0), pref * S * S)
    _CG_EXACT[key] = res
    return res


_CG_MP = {}


def cg(j1, m1, j2, m2, J, M):
    key = (mp.prec, j1, m1, j2, m2, J, M)
    v = _CG_MP.get(key)
    if v is None:
        s, v2 = cg_exact(j1, m1, j2, m2, J, M)
        v = mpf(0) if s == 0 else s * mp.sqrt(mpf(v2.numerator) / v2.denominator)
        _CG_MP[key] = v
    return v


_COUPLE_TAB = {}


def couple_table(j1, j2, J):
    key = (mp.prec, j1, j2, J)
    t = _COUPLE_TAB.get(key)
    if t is None:
        t = []
        for M in range(-J, J + 1):
            row = []
            for m1 in range(-j1, j1 + 1):
                m2 = M - m1
                if abs(m2) <= j2:
                    c = cg(j1, m1, j2, m2, J, M)
                    if c != 0:
                        row.append((m1 + j1, m2 + j2, c))
            t.append(row)
        _COUPLE_TAB[key] = t
    return t


def couple(x, j1, y, j2, J):
    """[x (x) y]_J."""
    t = couple_table(j1, j2, J)
    return [mp.fsum(c * x[i1] * y[i2] for (i1, i2, c) in row) if row else mpc(0) for row in t]


# ----------------------------------------------------------------------------------
# vectors, time reversal, D-matrices
# ----------------------------------------------------------------------------------
def theta(x):
    """Theta(sum u_m v_m) = sum (-1)^m conj(u_m) v_{-m} on V_j, j integer."""
    j = (len(x) - 1) // 2
    return [((-1) ** (m % 2)) * mp.conj(x[-m + j]) for m in range(-j, j + 1)]


def vdot(x, y):  # <x,y>, antilinear in x
    return mp.fsum(mp.conj(a) * b for a, b in zip(x, y))


def vnorm2(x):
    return mp.fsum(abs(a) ** 2 for a in x)


def vadd(x, y, c=1):
    return [a + c * b for a, b in zip(x, y)]


def vscale(x, c):
    return [c * a for a in x]


def basis_vec(j, m):
    v = [mpc(0)] * (2 * j + 1)
    v[m + j] = mpc(1)
    return v


def wigner_D(tj, g):
    """D^{tj/2}(g) as a list of rows, index i = (tm + tj)/2 for tm = -tj, -tj+2, ..., tj."""
    a, b = g[0]
    c, d = g[1]
    n = tj
    D = [[mpc(0)] * (n + 1) for _ in range(n + 1)]
    apow = [mpc(1)]
    bpow = [mpc(1)]
    cpow = [mpc(1)]
    dpow = [mpc(1)]
    for _ in range(n):
        apow.append(apow[-1] * a)
        bpow.append(bpow[-1] * b)
        cpow.append(cpow[-1] * c)
        dpow.append(dpow[-1] * d)
    for ip in range(n + 1):  # column: v_{m'} with p = j+m' = ip, q = n - ip
        p, q = ip, n - ip
        for r in range(n + 1):  # row: v_m with r = j+m
            s = mpc(0)
            for k in range(max(0, r - q), min(p, r) + 1):
                l = r - k
                s += comb(p, k) * comb(q, l) * apow[k] * cpow[p - k] * bpow[l] * dpow[q - l]
            D[r][ip] = s * mp.sqrt(mpf(fac(r) * fac(n - r)) / (fac(p) * fac(q)))
    return D


def mat_mul(A, B):
    n, k, m = len(A), len(B), len(B[0])
    return [[mp.fsum(A[i][t] * B[t][j] for t in range(k)) for j in range(m)] for i in range(n)]


def mat_vec(A, x):
    return [mp.fsum(a * b for a, b in zip(row, x)) for row in A]


def mat_adj(A):
    return [[mp.conj(A[i][j]) for i in range(len(A))] for j in range(len(A[0]))]


def mat_conj(A):
    return [[mp.conj(a) for a in row] for row in A]


def mat_maxdiff(A, B):
    return max(abs(a - b) for ra, rb in zip(A, B) for a, b in zip(ra, rb))


def col(A, a):
    return [row[a] for row in A]


def spin_matrices(j):
    """Explicit J_x, J_y, J_z on V_j (Condon-Shortley J_+)."""
    n = 2 * j + 1
    Jp = [[mpc(0)] * n for _ in range(n)]
    Jz = [[mpc(0)] * n for _ in range(n)]
    for m in range(-j, j + 1):
        Jz[m + j][m + j] = mpc(m)
        if m < j:
            Jp[m + 1 + j][m + j] = mpc(mp.sqrt((j - m) * (j + m + 1)))
    Jm = mat_adj(Jp)
    Jx = [[(Jp[i][k] + Jm[i][k]) / 2 for k in range(n)] for i in range(n)]
    Jy = [[(Jp[i][k] - Jm[i][k]) / mpc(0, 2) for k in range(n)] for i in range(n)]
    return Jx, Jy, Jz


