# quaternion -> SU(2) identifications
# ----------------------------------------------------------------------------------
def quat_to_su2(q, ident='A'):
    """ident A: i,j,k -> -i sigma_x, -i sigma_y, -i sigma_z.
       ident B: i,j,k ->  i sigma_z,  i sigma_y,  i sigma_x (orientation of the axes swapped)."""
    w, x, y, z = [c.to_mp() if isinstance(c, Q5) else mpf(c) for c in q]
    I = mpc(0, 1)
    if ident == 'A':
        return [[w - I * z, -y - I * x], [y - I * x, w + I * z]]
    if ident == 'B':
        # w + x(i s_z) + y(i s_y) + z(i s_x)
        return [[w + I * x, y + I * z], [-y + I * z, w - I * x]]
    raise ValueError(ident)


