def _pseudo_random_matrix(n, m, seed):
    # deterministic, reproducible "generic" entries
    out = []
    for i in range(n):
        row = []
        for k in range(m):
            t = (seed * 7919 + i * 104729 + k * 1299709) % 1000003
            u = (seed * 31 + i * 17 + k * 13 + 5) % 997
            row.append(mpc(mpf(t) / 1000003 - mpf(1) / 2, mpf(u) / 997 - mpf(1) / 3))
        out.append(row)
    return out


def gram_schmidt_frob(mats, d, tol):
    """Orthonormalise (2J+1) x d matrices so that eta^dagger eta = I and eta^dagger eta' = 0
    (by Schur these are multiples of I, so Frobenius orthogonality suffices)."""
    basis = []
    for X in mats:
        Y = [row[:] for row in X]
        for B in basis:
            c = mp.fsum(mp.conj(b) * y for rb, ry in zip(B, Y) for b, y in zip(rb, ry)) / d
            Y = [[y - c * b for y, b in zip(ry, rb)] for ry, rb in zip(Y, B)]
        nrm = mp.sqrt(mp.fsum(abs(y) ** 2 for ry in Y for y in ry) / d)
        if nrm > tol:
            basis.append([[y / nrm for y in ry] for ry in Y])
    return basis


def theta_cols(X):
    n = len(X)
    d = len(X[0])
    cols = [theta(col(X, a)) for a in range(d)]
    return [[cols[a][i] for a in range(d)] for i in range(n)]


class Setup:
    """All Gamma-dependent data at the current mp precision."""

    def __init__(self, ident='A', jmax=9):
        self.ident = ident
        self.jmax = jmax
        self.G = group()
        self.su2 = [quat_to_su2(h, ident) for h in self.G]
        self.idx_q1 = self.G.index(Q1)
        self.idx_q2 = self.G.index(Q2)
        self.Dcache = {}
        self.tol = mpf(10) ** (-(mp.dps // 2))
        self._decompose_V3()
        self.sectors = {}
        for name in ('3', '4'):
            self.sectors[name] = Sector(self, name)

    def D(self, j, i):
        key = (j, i)
        if key not in self.Dcache:
            self.Dcache[key] = wigner_D(2 * j, self.su2[i])
        return self.Dcache[key]

    def _decompose_V3(self):
        n = len(self.G)
        M = _pseudo_random_matrix(7, 7, 1)
        M = [[(M[i][k] + mp.conj(M[k][i])) / 2 for k in range(7)] for i in range(7)]
        C = [[mpc(0)] * 7 for _ in range(7)]
        for i in range(n):
            D = self.D(3, i)
            T = mat_mul(mat_mul(D, M), mat_adj(D))
            C = [[C[r][s] + T[r][s] / n for s in range(7)] for r in range(7)]
        E, Q = mp.eighe(mp.matrix(C))
        ev = [E[k] for k in range(7)]
        # cluster eigenvalues
        groups = []
        for k in range(7):
            for gp in groups:
                if abs(ev[gp[0]] - ev[k]) < self.tol:
                    gp.append(k)
                    break
            else:
                groups.append([k])
        self.commutant_eigen_groups = [(ev[g[0]], len(g)) for g in groups]
        self.projectors = {}
        for gp in groups:
            P = [[mp.fsum(Q[r, k] * mp.conj(Q[s, k]) for k in gp) for s in range(7)] for r in range(7)]
            self.projectors[str(len(gp))] = P


class Sector:
    def __init__(self, S, name):
        self.S = S
        self.name = name
        P = S.projectors[name]
        d = int(name)
        self.d = d
        # Theta-real orthonormal basis of the constituent
        cand = []
        for k in range(7):
            x = [P[r][k] for r in range(7)]
            for y in (vadd(x, theta(x)), vscale(vadd(x, theta(x), -1), mpc(0, 1))):
                cand.append([[c] for c in y])
        vecs = gram_schmidt_frob(cand, 1, S.tol)[:d]
        self.eta3 = [[vecs[a][r][0] for a in range(d)] for r in range(7)]
        # sigma(h) = eta^dagger D^3(h) eta for every element
        self.sigma = [mat_mul(mat_adj(self.eta3), mat_mul(S.D(3, i), self.eta3)) for i in range(len(S.G))]
        self.eta = {}
        self.eta[3] = [self.eta3]
        for J in range(0, S.jmax + 1):
            if J == 3:
                continue
            self.eta[J] = self._intertwiners(J)
        self._rs = {}
        self._mc = {}
        self.max_expand_residual = mpf(0)
        self.max_dropped_r = mpf(0)

    def _intertwiners(self, J):
        S = self.S
        n = 2 * J + 1
        d = self.d
        imgs = []
        for seed in range(1, 4):
            X = _pseudo_random_matrix(n, d, 100 * J + seed)
            R = [[mpc(0)] * d for _ in range(n)]
            for i in range(len(S.G)):
                T = mat_mul(mat_mul(S.D(J, i), X), mat_adj(self.sigma[i]))
                R = [[R[r][a] + T[r][a] for a in range(d)] for r in range(n)]
            R = [[x / len(S.G) for x in row] for row in R]
            imgs.append(R)
            # Theta-real combinations
        real = []
        for R in imgs:
            TR = theta_cols(R)
            real.append([[x + y for x, y in zip(r1, r2)] for r1, r2 in zip(R, TR)])
            real.append([[mpc(0, 1) * (x - y) for x, y in zip(r1, r2)] for r1, r2 in zip(R, TR)])
        return gram_schmidt_frob(real, d, S.tol)

    def dim(self, J):
        return len(self.eta.get(J, []))

    # --- Gamma constants ---------------------------------------------------------
    def rs(self, J1, al, J2, be, K):
        """r = sum_a [Theta eta^al_{J1}[:,a] (x) eta^be_{J2}[:,a]]_K (a Gamma-invariant vector in V_K)."""
        key = (J1, al, J2, be, K)
        if key not in self._rs:
            e1 = self.eta[J1][al]
            e2 = self.eta[J2][be]
            r = [mpc(0)] * (2 * K + 1)
            for a in range(self.d):
                r = vadd(r, couple(theta(col(e1, a)), J1, col(e2, a), J2, K))
            self._rs[key] = r
        return self._rs[key]

    def mulcoef(self, rkey, r, K, J2, be, J):
        """[r (x) eta^be_{J2}]_J (columnwise) expanded in the eta_J basis."""
        key = (rkey, J2, be, J)
        if key not in self._mc:
            e2 = self.eta[J2][be]
            cols = [couple(r, K, col(e2, a), J2, J) for a in range(self.d)]
            T = [[cols[a][k] for a in range(self.d)] for k in range(2 * J + 1)]
            coefs = []
            for eg in self.eta.get(J, []):
                c = mp.fsum(mp.conj(eg[k][a]) * T[k][a] for k in range(2 * J + 1) for a in range(self.d)) / self.d
                coefs.append(c)
            # residual of the expansion (must vanish: products of sections are sections)
            res = mpf(0)
            for k in range(2 * J + 1):
                for a in range(self.d):
                    v = T[k][a] - mp.fsum(c * eg[k][a] for c, eg in zip(coefs, self.eta.get(J, [])))
                    res = max(res, abs(v))
            self.max_expand_residual = max(self.max_expand_residual, res)
            self._mc[key] = coefs
        return self._mc[key]

    # --- section algebra -----------------------------------------------------------
    def scal(self, A, B):
        """Pointwise sum_a conj(A_a) B_a as a scalar function {K: [(s, rkey, r)]}."""
        out = {}
        tiny = mpf(10) ** (-(mp.dps - 8))
        for J1, us in A.items():
            for al, u in enumerate(us):
                tu = theta(u)
                for J2, vs in B.items():
                    for be, v in enumerate(vs):
                        for K in range(abs(J1 - J2), J1 + J2 + 1):
                            r = self.rs(J1, al, J2, be, K)
                            nr = mp.sqrt(vnorm2(r))
                            if nr < tiny:
                                self.max_dropped_r = max(self.max_dropped_r, nr)
                                continue
                            s = couple(tu, J1, v, J2, K)
                            out.setdefault(K, []).append((s, ('rs', J1, al, J2, be, K, 0), r))
        return out

    @staticmethod
    def conjf(f):
        out = {}
        for K, lst in f.items():
            out[K] = [(theta(s), rk[:-1] + (1 - rk[-1],), theta(r)) for (s, rk, r) in lst]
        return out

    @staticmethod
    def addf(f, h):
        out = {K: list(v) for K, v in f.items()}
        for K, v in h.items():
            out.setdefault(K, []).extend(v)
        return out

    def mul(self, f, B, Jset):
        out = {J: [[mpc(0)] * (2 * J + 1) for _ in self.eta[J]] for J in Jset if self.dim(J) > 0}
        for K, lst in f.items():
            for (s, rk, r) in lst:
                for J2, vs in B.items():
                    for be, v in enumerate(vs):
                        for J in out:
                            if not (abs(K - J2) <= J <= K + J2):
                                continue
                            coefs = self.mulcoef(rk, r, K, J2, be, J)
                            if all(abs(c) == 0 for c in coefs):
                                continue
                            left = couple(s, K, v, J2, J)
                            for g_, c in enumerate(coefs):
                                out[J][g_] = vadd(out[J][g_], left, c)
        return out

    def N(self, Phi, Jset=range(0, 10)):
        return self.mul(self.scal(Phi, Phi), Phi, Jset)

    def DN(self, Phi, h, Jset=(3,)):
        sp = self.scal(Phi, h)
        f = self.addf(sp, self.conjf(sp))
        a = self.mul(f, Phi, Jset)
        b = self.mul(self.scal(Phi, Phi), h, Jset)
        return sec_add(a, b)

    def inner(self, A, B):
        s = mpc(0)
        for J in A:
            if J in B:
                for u, v in zip(A[J], B[J]):
                    s += vdot(u, v) * self.d / (2 * J + 1)
        return s

    def norm2(self, A):
        return mp.re(self.inner(A, A))

    def level_norm2(self, A, J):
        return mp.fsum(vnorm2(u) for u in A.get(J, [])) * self.d / (2 * J + 1)

    def block(self, u):
        """Normalized block section of fibre vector u."""
        n2 = vnorm2(u) * self.d / 7
        return {3: [vscale(u, 1 / mp.sqrt(n2))]}


def sec_add(A, B, c=1):
    out = {J: [list(u) for u in us] for J, us in A.items()}
    for J, vs in B.items():
        if J not in out:
            out[J] = [vscale(v, c) for v in vs]
        else:
            out[J] = [vadd(u, v, c) for u, v in zip(out[J], vs)]
    return out


def sec_scale(A, c):
    return {J: [vscale(u, c) for u in us] for J, us in A.items()}


# ----------------------------------------------------------------------------------
# rotations, the left action on fibre vectors, and the stabilizers of item 3
# ----------------------------------------------------------------------------------
def rot(n, th):
    """cos(th/2) I - i sin(th/2) n.sigma  (rotation by th about the unit axis n)."""
    nx, ny, nz = [mpf(x) for x in n]
    nr = mp.sqrt(nx * nx + ny * ny + nz * nz)
    nx, ny, nz = nx / nr, ny / nr, nz / nr
    c, s = mp.cos(mpf(th) / 2), mp.sin(mpf(th) / 2)
    I = mpc(0, 1)
    return [[c - I * s * nz, -I * s * (nx - I * ny)], [-I * s * (nx + I * ny), c + I * s * nz]]


def rho_left(j, g):
    """Left translation on fibre vectors: (r.psi)(g) = psi(r^-1 g)  <=>  u -> conj(D^j(r)) u."""
    return mat_conj(wigner_D(2 * j, g))


def stabilizer_generators():
    """Closed-form generators of the stabilizers found in s03, with the character on Phi.
    Continuous parts are represented by one generic element (angle 1 rad)."""
    pi = mp.pi
    e = lambda x: mp.expjpi(x)  # exp(i pi x)
    return {
        'U1': [(rot((0, 0, 1), 1), mp.exp(mpc(0, 3)))],
        'U2': [(rot((0, 0, 1), 1), mpc(1)), (rot((1, 0, 0), pi), mpc(-1))],
        'U3': [(rot((0, 0, 1), pi / 2), mpc(-1)), (rot((1, 1, 0), pi / 2), mpc(-1))],
        'U4': [(rot((0, 0, 1), pi / 3), mpc(-1)), (rot((1, 0, 0), pi), mpc(-1))],
        'U5': [(rot((0, 0, 1), 2 * pi / 5), e(mpf(4) / 5))],
        'U6': [(rot((0, 0, 1), 2 * pi / 3), mpc(1)), (rot((1, 0, 0), pi), mpc(-1))],
    }


