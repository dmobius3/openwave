# ----------------------------------------------------------------------------------
# exact arithmetic in Q(sqrt5) and quaternions over it
# ----------------------------------------------------------------------------------
class Q5:
    """a + b*sqrt(5), a, b rational."""
    __slots__ = ('a', 'b')

    def __init__(self, a, b=0):
        self.a = Fraction(a)
        self.b = Fraction(b)

    def __add__(s, o):
        o = o if isinstance(o, Q5) else Q5(o)
        return Q5(s.a + o.a, s.b + o.b)
    __radd__ = __add__

    def __sub__(s, o):
        o = o if isinstance(o, Q5) else Q5(o)
        return Q5(s.a - o.a, s.b - o.b)

    def __rsub__(s, o):
        return Q5(o) - s

    def __neg__(s):
        return Q5(-s.a, -s.b)

    def __mul__(s, o):
        o = o if isinstance(o, Q5) else Q5(o)
        return Q5(s.a * o.a + 5 * s.b * o.b, s.a * o.b + s.b * o.a)
    __rmul__ = __mul__

    def __truediv__(s, o):
        o = o if isinstance(o, Q5) else Q5(o)
        n = o.a * o.a - 5 * o.b * o.b
        return s * Q5(o.a / n, -o.b / n)

    def __eq__(s, o):
        o = o if isinstance(o, Q5) else Q5(o)
        return s.a == o.a and s.b == o.b

    def __hash__(s):
        return hash((s.a, s.b))

    def to_mp(s):
        return mpf(s.a.numerator) / s.a.denominator + mpf(s.b.numerator) / s.b.denominator * mp.sqrt(5)

    def __repr__(s):
        if s.b == 0:
            return str(s.a)
        if s.a == 0:
            return '(%s*sqrt(5))' % s.b
        return '(%s%s%s*sqrt(5))' % (s.a, '+' if s.b > 0 else '-', abs(s.b))


PHI = Q5(Fraction(1, 2), Fraction(1, 2))
PHI_INV = PHI - 1


def qmul(p, q):
    w1, x1, y1, z1 = p
    w2, x2, y2, z2 = q
    return (w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2,
            w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
            w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2,
            w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2)


def qinv(p):  # unit quaternions only
    return (p[0], -p[1], -p[2], -p[3])


def qnorm2(p):
    return p[0] * p[0] + p[1] * p[1] + p[2] * p[2] + p[3] * p[3]


HALF = Fraction(1, 2)
Q1 = (Q5(HALF), Q5(HALF), Q5(HALF), Q5(HALF))
Q2 = (PHI * HALF, PHI_INV * HALF, Q5(HALF), Q5(0))
ONE = (Q5(1), Q5(0), Q5(0), Q5(0))


def closure(gens):
    """Group generated by `gens` (finite), by breadth-first multiplication."""
    elems = [ONE]
    seen = {ONE}
    frontier = [ONE]
    while frontier:
        new = []
        for e in frontier:
            for g in gens:
                h = qmul(e, g)
                if h not in seen:
                    seen.add(h)
                    elems.append(h)
                    new.append(h)
        frontier = new
    return elems


_GROUP = None


def group():
    global _GROUP
    if _GROUP is None:
        _GROUP = closure([Q1, Q2])
    return _GROUP


def chebU(n, w):
    """Chebyshev U_n(w) exactly (w in Q5); trace of D^{n/2} at an element with real part w."""
    if n == 0:
        return Q5(1)
    a, b = Q5(1), 2 * w
    for _ in range(n - 1):
        a, b = b, 2 * w * b - a
    return b


