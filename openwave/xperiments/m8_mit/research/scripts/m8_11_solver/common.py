"""Shared machinery for the worklist scripts.

Everything is derived from the two quaternion generators; no tables are used.

Conventions (see worklist.md section 1):
  * spins are integers here except where a doubled spin `tj` is used for D-matrices;
  * a vector in V_j is a list of length 2j+1, index i <-> weight m = i - j;
  * D^j(g) is built from the 2x2 matrix g = [[a,b],[c,d]] by the substitution
    x -> a x + c y, y -> b x + d y on v_m = x^(j+m) y^(j-m)/sqrt((j+m)!(j-m)!),
    which gives D^(1/2)(g) = g and the Condon-Shortley J_+ (checked in item0/item1);
  * a section at level 2J is stored as {J: [u_0, u_1, ...]} with one fibre vector per
    kept intertwiner eta_J[gamma]; the section is sum_gamma u_gamma (x) eta_J[gamma];
  * a right-Gamma-invariant scalar function is stored as {K: [(s, r), ...]}, meaning
    sum s_M D^K_{MK'}(g) r_K'.
"""
import os, sys, json
from fractions import Fraction
from math import factorial as fac, comb
from mpmath import mp, mpf, mpc

HERE = os.path.dirname(os.path.abspath(__file__))
